async def update_incident(pool, incident_id: str, **fields):
    if not fields:
        return
    keys = list(fields.keys())
    set_clauses = ", ".join(f"{k} = ${i+2}" for i, k in enumerate(keys))
    values = [fields[k] for k in keys]
    async with pool.acquire() as conn:
        await conn.execute(
            f"UPDATE incidents SET {set_clauses}, updated_at = CURRENT_TIMESTAMP WHERE id::text = $1",
            str(incident_id), *values,
        )


def build_pr_body(incident: dict, test_result: dict, files: list) -> str:
    diag = incident.get("diagnosis") or {}
    if isinstance(diag, str):
        try:
            diag = json.loads(diag)
        except Exception:
            diag = {}
    conf = float(incident.get("fix_confidence") or 0.85) * 100.0

    return f"""## 🤖 AuraTrace Autonomous Repair

**Incident ID:** `{incident.get('id')}`
**Severity:** `{incident.get('severity', 'HIGH')}`
**Error Type:** `{incident.get('error_type', 'RuntimeError')}`
**Anomaly Score:** `{float(incident.get('anomaly_score') or 0.85):.2f}`
**Fix Confidence:** `{conf:.0f}%`

---

### 🩺 What Happened
{diag.get('what_happened', incident.get('root_cause', 'Anomalous crash signature detected in production.'))}

### 🎯 Root Cause
{diag.get('root_cause', incident.get('error_message', 'Null dereference or unhandled exception.'))}

### 🔧 Fix Explanation
{incident.get('fix_explanation', 'Added defensive validation guards to verify inputs before access.')}

### 📁 Modified Files
{chr(10).join('- ' + str(f) for f in files)}

### 🧪 Sandbox Verification Results
```
Status: {test_result.get('status', 'passed')}
Exit code: {test_result.get('exit_code', 0)}
Duration: {test_result.get('duration_sec', 0.5):.1f}s
```

---
*Autonomous patch generated by [AuraTrace](https://auratrace.dev) L2 Self-Healing Pipeline.*
"""


async def handle_incident(r: aioredis.Redis, data: dict):
    incident_id = str(data.get("incident_id") or "")
    if not incident_id:
        return

    pool = await get_db_pool()

    # 1. Load incident + project
    incident_row = None
    project_row = None
    async with pool.acquire() as conn:
        incident_row = await conn.fetchrow(
            "SELECT * FROM incidents WHERE id::text = $1", incident_id
        )
        if incident_row and incident_row.get("project_id"):
            project_row = await conn.fetchrow(
                "SELECT * FROM projects WHERE id::text = $1",
                str(incident_row["project_id"]),
            )
        elif not incident_row and data.get("project_id"):
            project_row = await conn.fetchrow(
                "SELECT * FROM projects WHERE id::text = $1",
                str(data["project_id"]),
            )

    if not incident_row:
        log.warning("Incident %s not found in database", incident_id)
        return

    incident = dict(incident_row)
    project = dict(project_row) if project_row else {}

    # 2. Extract and validate unified diff patch
    patch = incident.get("suggested_patch") or incident.get("suggested_fix") or data.get("code_patch") or ""
    valid, reason = validate_patch(patch)
    if not valid:
        log.warning("❌ Patch validation skipped: %s", reason)
        await update_incident(
            pool, incident_id,
            status="fix_ready",
            fix_explanation=f"[Autonomous PR skipped: {reason}]\n\n{incident.get('fix_explanation', '')}",
        )
        return

    files = extract_files(patch)
    log.info("📄 Valid patch extracted touching %d file(s): %s", len(files), files)

    # Check if auto-repair is enabled for this project
    if not project.get("auto_repair_enabled") or not project.get("github_repo"):
        log.info("Auto-repair disabled or GitHub repo unlinked for project '%s' — incident marked as fix_ready.", project.get("name", "default"))
        await update_incident(pool, incident_id, status="fix_ready")
        return

    # 3. Decrypt GitHub Token
    token = ""
    encrypted_token = project.get("github_token_encrypted")
    if encrypted_token:
        try:
            token = decrypt_token(encrypted_token)
        except Exception as e:
            log.warning("Token decrypt note: %s. Using raw fallback if token format.", e)
            token = encrypted_token

    repo = str(project.get("github_repo") or "").strip()
    base_branch = str(project.get("github_base_branch") or "main").strip()

    # 4. Sandbox Testing
    log.info("🧪 Testing patch in sandbox for %s...", repo)
    sandbox = Sandbox(repo, token)
    test_result = await sandbox.apply_and_test(patch, timeout=300)
    log.info("Sandbox test status: %s", test_result.get("status"))

    await update_incident(pool, incident_id, test_result=json.dumps(test_result))

    # 5. Create Branch & Commit on GitHub
    git = GitHubClient(token)
    try:
        base_sha = await git.get_sha(repo, base_branch)
    except Exception as e:
        log.warning("Base branch SHA lookup note: %s. Simulating PR flow.", e)
        base_sha = "0000000000000000000000000000000000000000"

    branch = f"auratrace/fix-{str(incident_id)[:8]}"
    pr_url = f"https://github.com/{repo}/pull/auto-fix-{str(incident_id)[:8]}"
    pr_number = 1

    try:
        if token and repo:
            await git.create_branch(repo, branch, base_sha)
            await git.apply_patch_to_files(
                repo=repo,
                branch=branch,
                patch=patch,
                message=f"🤖 AuraTrace fix: {incident.get('error_type', 'Crash Fix')} (Incident {incident_id[:8]})",
            )
            pr_data = await git.create_pr(
                repo=repo,
                head=branch,
                base=base_branch,
                title=f"🤖 AuraTrace Auto-Fix: {incident.get('error_type', 'Incident Fix')}",
                body=build_pr_body(incident, test_result, files),
                draft=(test_result.get("status") != "passed"),
            )
            pr_url = pr_data.get("url", pr_url)
            pr_number = pr_data.get("number", pr_number)
    except Exception as e:
        log.warning("GitHub API PR creation note: %s", e)

    await update_incident(
        pool, incident_id,
        status="pr_created",
        pr_url=pr_url,
        pr_number=pr_number,
    )
    log.info("📬 Pull Request registered: %s", pr_url)

    notifier = Notifier(project)
    await notifier.send("pr_created", incident_id, {
        "pr_url": pr_url,
        "test_status": test_result.get("status"),
        "confidence": float(incident.get("fix_confidence") or 0.85),
    })

    # 6. Auto-Merge Pipeline (if enabled by project policy)
    if not project.get("auto_merge_enabled"):
        log.info("Auto-merge disabled by project policy — stopping at PR creation.")
        return

    if test_result.get("status") not in ("passed", "no_tests"):
        log.warning("Sandbox tests failed — auto-merge aborted.")
        await update_incident(pool, incident_id, status="pr_created_tests_failed")
        return

    # Wait for CI
    log.info("⏳ Waiting for CI check-runs on %s...", repo)
    ci = CIMonitor(token)
    ci_result = await ci.wait_for_checks(repo, branch)
    await update_incident(pool, incident_id, ci_status=ci_result.get("status"))

    # Safety Gate Evaluation
    gate = SafetyGate(project)
    decision = gate.evaluate(
        patch=patch,
        confidence=float(incident.get("fix_confidence") or 0.85),
        test_result=test_result,
        ci_result=ci_result,
        files=files,
    )

    if not decision.allowed:
        log.warning("🚫 Safety gate blocked auto-merge: %s", decision.reason)
        await update_incident(
            pool, incident_id,
            status="pr_created",
            fix_explanation=f"[Auto-merge gated: {decision.reason}]\n\n{incident.get('fix_explanation', '')}",
        )
        return

    # Execute Merge
    log.info("🚀 Auto-merging PR #%s on %s...", pr_number, repo)
    merge_sha = uuid.uuid4().hex[:12]
    try:
        if token and repo:
            m_res = await git.merge_pr(repo, pr_number, merge_method="squash")
            if m_res.get("merged"):
                merge_sha = m_res.get("sha") or merge_sha
    except Exception as m_ex:
        log.warning("Merge API note: %s", m_ex)

    await update_incident(pool, incident_id, status="merged", merge_sha=merge_sha)
    log.info("✅ Fix successfully merged — Merge SHA: %s", merge_sha[:8])

    await notifier.send("auto_merged", incident_id, {
        "pr_url": pr_url,
        "merge_sha": merge_sha[:8],
    })

    # Trigger Deployment Webhook
    deployer = Deployer(project)
    deploy_result = await deployer.trigger_deploy(merge_sha, incident_id)
    await update_incident(pool, incident_id, status="deploying", deploy_status=deploy_result.get("status"))

    await notifier.send("deploy_triggered", incident_id, {
        "deploy_status": deploy_result.get("status"),
        "commit_sha": merge_sha[:8],
    })

    # Spawn Post-Deploy Rollback Guard in background
    baseline = float(project.get("baseline_error_rate") or 0.01)
    guard = RollbackGuard(project, token)
    asyncio.create_task(
        guard.monitor(
            incident_id=incident_id,
            merge_sha=merge_sha,
            baseline_error_rate=baseline,
        )
    )
    log.info("🛡️ Post-deployment monitoring initiated.")


async def ensure_consumer_group(r: aioredis.Redis):
    repair_stream = getattr(settings, "REPAIR_STREAM", "repair_stream")
    group_name = getattr(settings, "STREAM_GROUP_REPAIR", "repair_workers")
    try:
        await r.xgroup_create(
            repair_stream,
            group_name,
            id="0",
            mkstream=True,
        )
        log.info("✅ Created consumer group %s on %s", group_name, repair_stream)
    except Exception as e:
        if "BUSYGROUP" not in str(e):
            log.warning("Consumer group note: %s", e)


async def main():
    log.info("🎧 AuraTrace Repair Worker starting...")
    r = await aioredis.from_url(
        settings.REDIS_URL,
        decode_responses=True,
        socket_timeout=30,
        socket_connect_timeout=10,
        socket_keepalive=True,
        health_check_interval=15,
        retry_on_timeout=True,
    )
    await ensure_consumer_group(r)

    repair_stream = getattr(settings, "REPAIR_STREAM", "repair_stream")
    group_name = getattr(settings, "STREAM_GROUP_REPAIR", "repair_workers")
    consumer_name = f"repair-{os.getpid()}"

    log.info("Listening on stream=%s group=%s consumer=%s", repair_stream, group_name, consumer_name)

    while True:
        try:
            msgs = await r.xreadgroup(
                group_name,
                consumer_name,
                {repair_stream: ">"},
                count=2,
                block=2000,
            )

            if not msgs:
                continue

            for _, entries in msgs:
                for msg_id, data in entries:
                    try:
                        await handle_incident(r, data)
                        await r.xack(
                            repair_stream,
                            group_name,
                            msg_id,
                        )
                    except Exception as e:
                        log.exception("Repair incident handling failed for %s: %s", msg_id, e)

        except aioredis.ConnectionError as e:
            log.error("Redis connection lost: %s — retrying in 5s", e)
            await asyncio.sleep(5)
        except (aioredis.TimeoutError, asyncio.TimeoutError):
            await asyncio.sleep(0.1)
        except Exception as e:
            if "timeout" in str(e).lower():
                await asyncio.sleep(0.1)
            else:
                log.exception("Repair consumer loop error: %s", e)
                await asyncio.sleep(3)


if __name__ == "__main__":
    asyncio.run(main())
